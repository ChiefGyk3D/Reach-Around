"""Render the ``_redirects`` file from the validated ``redirects`` config.

The old ``/socials`` page can go to a configured root-relative target, and old
tab slugs can go to current tab routes. Every source is emitted with and without
a trailing slash. Each line is ``source destination status``, the Cloudflare
Pages ``_redirects`` format. The renderer enforces the host's 2,000 static-rule
limit before returning a file.
"""

from __future__ import annotations

from collections.abc import Mapping

from reach_around.config.redirects import SocialsRedirect, target_problem

SOCIALS_SOURCES = ("/socials", "/socials/")
REDIRECTS_FILE = "_redirects"
_STATUSES = (301, 302)
MAX_STATIC_RULES = 2000

_HEADER = (
    "# Generated by Reach Around from the redirects config.\n"
    "# The old /socials page goes to the link page.\n"
)


def render_redirects(
    socials: SocialsRedirect | None,
    tab_routes: Mapping[str, str] | None = None,
) -> str:
    """Return the ``_redirects`` text for ``socials``.

    The model already validates both fields; this checks them again so a value
    that skipped validation can never add a line, a second rule or an off-site
    destination.
    """
    rule_count = 2 * (len(tab_routes or {}) + (socials is not None))
    if rule_count > MAX_STATIC_RULES:
        raise ValueError(
            f"redirects config generates {rule_count:,} static rules; "
            f"Cloudflare Pages allows at most {MAX_STATIC_RULES:,}"
        )
    lines: list[str] = []
    if socials is not None:
        target = socials.target
        problem = target_problem(target)
        if problem:
            raise ValueError(f"redirect target: {problem}")
        status = socials.status
        if type(status) is not int or status not in _STATUSES:
            raise ValueError("redirect status must be 301 or 302")
        lines.extend(f"{source} {target} {status}" for source in SOCIALS_SOURCES)
    for old_slug, target in sorted((tab_routes or {}).items()):
        lines.extend(
            (
                f"/{old_slug} {target} 301",
                f"/{old_slug}/ {target} 301",
            )
        )
    return _HEADER + "\n".join(lines) + "\n"
