export function t(id, values) {
  const text = Object.hasOwn(STRINGS, id) ? STRINGS[id] : id;
  if (!values) {
    return text;
  }
  return text.replace(/\{(\w+)\}/g, (whole, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : whole,
  );
}
